pub fn get_scaled_character(c: char, x0: f32, y0: f32, width: usize) -> Vec<Path> {
    let ascii = c as u8 - 32u8;
    let path_original = HERSHEY[ascii as usize];
    let factor = width as f32 / HERSHEY_CHAR_WIDTH as f32;

    path_original.iter().map(|(p0, p1)| {
        Path::line(
          Point { x: x0 + p0.x * factor, y: y0 + (30.0 - p0.y) * factor },
          Point { x: x0 + p1.x * factor, y: y0 + (30.0 - p1.y) * factor }
        )
      }
    ).collect()
}
    